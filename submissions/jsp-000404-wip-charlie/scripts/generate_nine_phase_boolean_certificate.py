"""Generate an explicit Lean proof from finite Boolean unit propagation.

The generated proof only performs case splits and equality rewrites. No
external solver or proof-reflection axiom participates in its checking.
"""

import json
from itertools import combinations
from pathlib import Path
from check_nine_phase_capacity import indexed_catalog, SLOTS


rows = indexed_catalog()
active = [i for i, (p, n) in enumerate(rows) if (p | n).bit_count() == 6]
clauses = []
for word in SLOTS:
    indices = [i for i in active if word & rows[i][0] == rows[i][0] and word & rows[i][1] == 0]
    if indices:
        clauses.append([(i, True) for i in indices])
for i, j in combinations(active, 2):
    p, n = rows[i]
    a, b = rows[j]
    if not (p & b or n & a):
        clauses.append([(i, False), (j, False)])
for core in [[25, 54, 70, 11, 44], [24, 55, 71, 10, 45]]:
    clauses.append([(i, False) for i in core])
used = set()
nodes = 0


def reduced(clause, assignment):
    if any(assignment.get(i) == value for i, value in clause):
        return None
    return [(i, value) for i, value in clause if i not in assignment]


def derive(clause_index, assignment, indent, contradiction=False):
    used.add(clause_index)
    names = [f'hx{i}' for i, _ in clauses[clause_index] if i in assignment]
    names += ['Bool.false_eq_true', 'Bool.true_eq_false', 'false_or', 'or_false']
    ending = f'] at h{clause_index}' if contradiction else f'] using h{clause_index}'
    result = []
    line = indent + ('simpa' if not contradiction else 'simp') + ' only ['
    for index, name in enumerate(names):
        fragment = name + (', ' if index < len(names) - 1 else '')
        if len(line) + len(fragment) + len(ending) > 100:
            result.append(line.rstrip())
            line = indent + '  '
        line += fragment
    result.append(line + ending)
    return result


def search(assignment, indent):
    global nodes
    nodes += 1
    output = []
    while True:
        unit = None
        remaining = []
        for number, clause in enumerate(clauses):
            new = reduced(clause, assignment)
            if new is None:
                continue
            if not new:
                output.extend(derive(number, assignment, indent, contradiction=True))
                return output
            if len(new) == 1:
                unit = number, new[0]
                break
            remaining.append(new)
        if unit is None:
            break
        number, (i, value) = unit
        output.append(indent + f'have hx{i} : x{i} = {str(value).lower()} := by')
        output.extend(derive(number, assignment, indent + '  '))
        assignment[i] = value
    if not remaining:
        raise AssertionError('The proposed Boolean constraints are satisfiable')
    shortest = min(remaining, key=len)
    variable = max((i for i, _ in shortest),
                   key=lambda i: sum(any(j == i for j, _ in clause) for clause in remaining))
    output.append(indent + f'cases hx{variable} : x{variable} with')
    for value in (False, True):
        output.append(indent + f'| {str(value).lower()} =>')
        output.extend(search(dict(assignment, **{}) | {variable: value}, indent + '  '))
    return output


proof = search({}, '  ')
binders = []
for start in range(0, len(active), 12):
    binders.append('    (' + ' '.join(f'x{i}' for i in active[start:start + 12]) + ' : Bool)')
for number in sorted(used):
    clause = clauses[number]
    line = f'    (h{number} : '
    for index, (i, value) in enumerate(clause):
        fragment = f'x{i} = {str(value).lower()}' + (' ∨ ' if index < len(clause) - 1 else ')')
        if len(line) + len(fragment) > 100:
            binders.append(line.rstrip())
            line = '      '
        line += fragment
    binders.append(line)
result = '\n'.join(['import Mathlib.Tactic', '', '/-!',
                    '# Explicit Boolean certificate for nine-phase saturation', '',
                    'Generated by `scripts/generate_nine_phase_boolean_certificate.py`.',
                    'The proof consists solely of Boolean cases and equality simplifications.',
                    'Its assumptions are connected to row geometry in a separate module.', '-/', '',
                    'namespace JSP000404Research.NinePhase.BooleanCertificate', '',
                    'set_option maxRecDepth 16384',
                    'set_option maxHeartbeats 4000000', '',
                    'theorem clauses_impossible', *binders,
                    '    : False := by', *proof, '',
                    '#print axioms clauses_impossible', '',
                    'end JSP000404Research.NinePhase.BooleanCertificate', ''])
assert all(len(line) <= 100 for line in result.splitlines())
Path('JSP000404Research/NinePhaseBooleanCertificate.lean').write_text(
    result, encoding='utf-8', newline='\n')
Path('artifacts/nine-phase-boolean-certificate.json').write_text(json.dumps(dict(
    clauses=clauses, used=sorted(used), nodes=nodes, lines=len(result.splitlines())), indent=2))
print('Generated proof:', nodes, 'nodes;', len(used), '/', len(clauses), 'clauses;', len(proof), 'lines')
